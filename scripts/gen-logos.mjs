/**
 * Generates lib/brand-logos.ts from the pinned `simple-icons` dev dependency (CC0 SVG data).
 * Only the marks for apps in lib/provider-directory.ts are emitted, so the client bundle carries
 * ~100 paths instead of the whole set. Logos remain trademarks of their owners.
 *
 *   node scripts/gen-logos.mjs
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const source = readFileSync("lib/provider-directory.ts", "utf8");
const names = [...source.matchAll(/\{ name: "([^"]+)"/g)].map((m) => m[1]);

const all = Object.values(icons).filter((i) => i && typeof i === "object" && i.path);
const norm = (s) => s.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]/g, "");
const byTitle = new Map(all.map((i) => [norm(i.title), i]));
const bySlug = new Map(all.map((i) => [i.slug, i]));

// Where the directory name and the Simple Icons title differ, or the mark lives under a parent brand.
const overrides = {
  "Google Drive": "googledrive",
  "Google Calendar": "googlecalendar",
  "Google Sheets": "googlesheets",
  "Google Docs": "googledocs",
  "Google Analytics": "googleanalytics",
  "Google Ads": "googleads",
  "YouTube": "youtube",
  "X (Twitter)": "x",
  "Twitter": "x",
  "Atlassian Jira": "jira",
  "Jira": "jira",
  "Confluence": "confluence",
  "Cal.com": "caldotcom",
  "Monday.com": "mondaydotcom",
  "monday.com": "mondaydotcom",
  "Zoho CRM": "zoho",
  "QuickBooks": "quickbooks",
  "Box": "box",
  "Microsoft Teams": "microsoftteams",
  "Microsoft Outlook": "microsoftoutlook",
  "OneDrive": "microsoftonedrive",
  "Microsoft OneDrive": "microsoftonedrive",
  "SharePoint": "microsoftsharepoint",
  "Microsoft SharePoint": "microsoftsharepoint",
};

const found = {};
const missing = [];
for (const name of names) {
  const icon = bySlug.get(overrides[name]) || byTitle.get(norm(name)) || bySlug.get(norm(name));
  if (icon) found[name] = { title: icon.title, hex: icon.hex, path: icon.path };
  else missing.push(name);
}

// Brands absent from Simple Icons: icons saved from each brand's own site by scripts/fetch-site-icons.mjs.
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const files = existsSync("public/logos") ? readdirSync("public/logos") : [];
const site = {};
for (const name of missing) {
  const file = files.find((f) => f.replace(/\.[^.]+$/, "") === slug(name));
  if (file) site[name] = `/logos/${file}`;
}

const body = Object.entries(found)
  .map(([name, i]) => `  ${JSON.stringify(name)}: { hex: "${i.hex}", path: ${JSON.stringify(i.path)} },`)
  .join("\n");
const siteBody = Object.entries(site)
  .map(([name, file]) => `  ${JSON.stringify(name)}: ${JSON.stringify(file)},`)
  .join("\n");
writeFileSync(
  "lib/brand-logos.ts",
  `// Generated by scripts/gen-logos.mjs. Do not edit by hand. Logos are trademarks of their respective owners.\n` +
    `// brandLogos: single-colour marks from simple-icons (CC0).\n` +
    `export const brandLogos: Record<string, { hex: string; path: string }> = {\n${body}\n};\n\n` +
    `// siteLogos: icons published on each brand's own site (see docs/logo-sources.json), served from /public.\n` +
    `export const siteLogos: Record<string, string> = {\n${siteBody}\n};\n`,
);
const none = missing.filter((n) => !site[n]);
console.log(`${Object.keys(found).length} Simple Icons marks, ${Object.keys(site).length} site icons, ${none.length} initials only: ${none.join(", ") || "none"}`);
